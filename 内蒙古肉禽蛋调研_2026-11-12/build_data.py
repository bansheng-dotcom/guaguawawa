# ---------- 7. 指标计算 ----------
def pct(a, b):
    return round((b - a) / a * 100, 2)

calc = {}
rows = []
for name, _, _, _, nov, oct_avg, *_ in impc:
    rows.append({"品类": name, "10月均": oct_avg, "11月5日": nov,
                 "11月vs10月%": pct(oct_avg, nov)})
calc["月度环比"] = rows

# 等权篮子
base = sum(r[5] for r in impc) / len(impc)
novb = sum(r[4] for r in impc) / len(impc)
calc["等权篮子"] = {"10月均值": round(base, 3), "11月5日": round(novb, 3), "变化%": pct(base, novb)}
# 贡献度
calc["贡献度"] = [{"品类": r["品类"], "贡献pp": round((r["11月5日"] - r["10月均"]) / len(impc), 3)} for r in rows]

# 批零价差
spread_src = [
    ("牛肉", 37.28, 36.00, "东瓦窑72元/公斤"),
    ("羊肉（去骨）", 39.56, 36.00, "东瓦窑72元/公斤"),
    ("白条鸡", 11.97, 8.50, "东瓦窑17元/公斤"),
    ("鸡蛋", 5.18, 4.965, "全国批发9.93元/公斤"),
    ("带鱼", 17.20, 16.00, "保全庄32元/公斤"),
    ("草鱼", 11.31, 8.50, "东瓦窑17元/公斤"),
    ("鲤鱼", 8.86, 6.50, "东瓦窑13元/公斤"),
]
spread = [{"品类": a, "零售": b, "批发": c, "批零倍数": round(b / c, 3),
           "中间加价%": pct(c, b), "批发口径": d} for a, b, c, d in spread_src]
calc["批零价差"] = spread

# 商务预报周度涨跌
calc["周度涨跌_末周vs首周"] = []
for i, h in enumerate(["牛腿肉", "羊腿肉", "禽类", "蛋类", "水产品"]):
    first, last = weekly[0][i + 1], weekly[-1][i + 1]
    calc["周度涨跌_末周vs首周"].append({"指标": h, "首周": first, "末周": last, "变化%": pct(first, last)})

