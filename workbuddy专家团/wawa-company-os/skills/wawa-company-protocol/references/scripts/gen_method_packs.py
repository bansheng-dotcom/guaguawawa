def render(rid: str, s: dict) -> str:
    tree = "\n".join(f"| {n} | {q} | {h} | {d} | {m} |" for n, q, h, d, m in s["branches"])
    methods = "\n".join(f"- {m}" for m in s["methods"])
    traps = "\n".join(f"- {t}" for t in s["traps"])
    return TEMPLATE.format(
        title=s["title"], decision=s["decision"], dm=s["dm"], success=s["success"], out=s["out"],
        tree=tree, critical=s["critical"],
        h1=s["hypotheses"][0], h2=s["hypotheses"][1],
        c1=s["competing"][0], c2=s["competing"][1],
        evidence=COMMON_EVIDENCE, methods=methods, traps=traps,
        extra=s.get("extra", ""), output=COMMON_OUTPUT,
    )


def main() -> None:
    for rid, spec in SPECS.items():
        d = next((p for p in ROOT.glob(f"{rid}-*") if p.is_dir()), None)
        if not d:
            print("skip", rid)
            continue
        ref = d / "references"
        ref.mkdir(exist_ok=True)
        (ref / "method-pack.md").write_text(render(rid, spec), encoding="utf-8")
        print("wrote", d.name)


if __name__ == "__main__":
    main()
